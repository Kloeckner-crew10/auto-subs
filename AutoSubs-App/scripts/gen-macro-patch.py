#!/usr/bin/env python3
"""Generate resources/modules/macro_patch.lua from the caption macro.

The bundled caption template (caption-bin.drb) can only be regenerated inside
Resolve, and Resolve 21.1 free blocks the updater script. But the macro keeps
its logic as script strings in tool data (`tool:GetData("ApplyHighlight")`),
so AutoSubs can install newer logic into each caption clip at placement time.

This script copies the keyword-aware chunks out of autosubs-macro.setting.
Old templates have no Keyword* inputs, so every `tool:GetInput("Keyword…")`
falls back to the `AutoSubsKeyword` table the app stores in tool data.

Run after editing the macro:  python3 scripts/gen-macro-patch.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MACRO = ROOT / "Resolve-Integration" / "autosubs-macro.setting"
OUT = ROOT / "AutoSubs-App" / "src-tauri" / "resources" / "modules" / "macro_patch.lua"
CHUNKS = ["ScaleWordTiming", "ApplyWordMarkers", "ApplyHighlight", "RemoveHighlight", "UpdateHighlight"]

FALLBACK = {
    "KeywordEnabled": "Enabled",
    "KeywordColorRed": "Red",
    "KeywordColorGreen": "Green",
    "KeywordColorBlue": "Blue",
}

text = MACRO.read_text(encoding="utf-8")
out = [
    "-- Generated by scripts/gen-macro-patch.py from Resolve-Integration/autosubs-macro.setting.",
    "-- Do not edit by hand. See caption_style.install_macro_patch.",
    "return {",
]
for name in CHUNKS:
    m = re.search(r"^\t\t\t\t" + name + r" = \[\[\n(.*?)\n\t\t\t\t\]\],$", text, re.S | re.M)
    if not m:
        raise SystemExit(f"chunk not found: {name}")
    body = m.group(1)
    for inp, field in FALLBACK.items():
        body = body.replace(
            f'tool:GetInput("{inp}")',
            f'(tool:GetInput("{inp}") or (tool:GetData("AutoSubsKeyword") or {{}}).{field})',
        )
    assert "]==]" not in body
    out.append(f"    {name} = [==[\n{body}\n]==],")
out.append("}")
OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)} ({len(CHUNKS)} chunks)")
